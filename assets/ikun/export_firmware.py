"""Extract existing IKUN atlas pixels into firmware GIFs; no artwork is redrawn."""
from pathlib import Path
import json
from PIL import Image

ROOT = Path(__file__).resolve().parent
BOARD = ROOT.parents[1] / 'xiaozhi-esp32/main/boards/waveshare/esp32-s3-touch-amoled-1.75'
STATES = {
    'idle': (0, [0, 1, 2, 3, 4, 5], [280, 110, 110, 140, 140, 320]),
    'listening': (6, list(range(6)), [150] * 5 + [260]),
    'thinking': (8, list(range(6)), [150] * 5 + [280]),
    'speaking': (7, list(range(6)), [120] * 5 + [220]),
    'happy': (4, list(range(5)), [140] * 4 + [280]),
    'sad': (5, list(range(8)), [140] * 7 + [240]),
    'waving': (3, list(range(4)), [140] * 3 + [280]),
    'sleepy': (0, [3, 5], [800, 800]),
}
sheet = Image.open(ROOT / 'spritesheet.png').convert('RGBA')
assert sheet.size == (1536, 1872)
header = ['// Generated by assets/ikun/export_firmware.py from owned pet IKUN.',
          '#pragma once', '#include <cstddef>', '#include <cstdint>',
          'namespace ikun {', 'struct Animation { const uint8_t* data; size_t size; };']
report = {}
for name, (row, columns, durations) in STATES.items():
    frames = []
    for column in columns:
        frame = sheet.crop((column * 192, row * 208, (column + 1) * 192, (row + 1) * 208))
        frame = frame.resize((216, 234), Image.Resampling.LANCZOS)
        alpha = frame.getchannel('A')
        pal = frame.convert('RGB').quantize(colors=64, dither=Image.Dither.NONE)
        palette = pal.getpalette()
        pal.putpalette(palette[:765] + [0, 0, 0])
        pal.paste(255, mask=alpha.point(lambda a: 255 if a < 128 else 0))
        frames.append(pal)
    output = ROOT / (name + '.gif')
    frames[0].save(output, save_all=True, append_images=frames[1:], duration=durations,
                   loop=0, transparency=255, disposal=2, optimize=False)
    with Image.open(output) as gif:
        assert gif.size == (216, 234)
        assert gif.n_frames == len(columns)
    data = output.read_bytes()
    header.append(f'inline constexpr uint8_t {name}_data[] = {{')
    for i in range(0, len(data), 16):
        header.append('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i+16]) + ',')
    header.extend(['};', f'inline constexpr Animation {name}{{{name}_data, sizeof({name}_data)}};'])
    report[name] = {'source_row': row, 'frames': len(columns), 'bytes': len(data), 'durations_ms': durations}
header.append('}  // namespace ikun')
(BOARD / 'ikun_assets.h').write_text('\n'.join(header) + '\n')
(ROOT / 'animations.json').write_text(json.dumps(report, ensure_ascii=False, indent=2))
print(json.dumps(report, indent=2))
